const fixture = `[local-db]
driver = "postgres"
host = "::1"
port = 5432
database = "demo"
username = "test user"
password = "secret@/?"
params = { sslmode = "disable" }
`

func setupCatalog(t *testing.T) string {
	t.Helper()
	t.Setenv("XDG_CONFIG_HOME", t.TempDir())
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "local.toml"), []byte(fixture), 0o600); err != nil {
		t.Fatal(err)
	}
	return dir
}

func TestInitSync(t *testing.T) {
	dir := setupCatalog(t)
	if err := storage.WritePrivate(defaultConfigPath(), []byte("tool = 'harlequin'\nconnection = 'local-db'\n[extra]\nkeep = true\n")); err != nil {
		t.Fatal(err)
	}
	if err := initializeSource(dir); err != nil {
		t.Fatal(err)
	}
	cfg, raw, err := loadDBConfig()
	if err != nil || cfg.ConnectionsDir != dir || raw["tool"] != nil || raw["connection"] != nil || raw["extra"] == nil {
		t.Fatalf("config not preserved: %v", err)
	}
	catalog, err := syncCatalog()
	if err != nil {
		t.Fatal(err)
	}
	if len(catalog) != 1 || catalog["local-db"].Driver != "postgres" {
		t.Fatal("incorrect catalog")
	}
	root := filepath.Join(configBase(), "db")
	path := filepath.Join(root, "harlequin.toml")
	info, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	if info.Mode().Perm() != 0o600 {
		t.Fatal("unsafe permissions")
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var parsed struct {
		Profiles map[string]struct {
			Adapter string
			ConnStr []string `toml:"conn_str"`
			Limit   int
		}
	}
	if _, err := toml.Decode(string(data), &parsed); err != nil {
		t.Fatal(err)
	}
	profile := parsed.Profiles["local_db"]
	if len(parsed.Profiles) != 1 || profile.Adapter != "postgres" || profile.Limit != 1000 || len(profile.ConnStr) != 1 || profile.ConnStr[0] != "postgresql://test%20user:secret%40%2F%3F@[::1]:5432/demo?sslmode=disable" {
		t.Fatal("native profile settings changed")
	}
	for _, name := range []string{"rainfrog_config.toml", "nvim"} {
		if _, err := os.Lstat(filepath.Join(root, name)); !os.IsNotExist(err) {
			t.Fatalf("auxiliary output created: %s", name)
		}
	}
	if _, err := syncCatalog(); err != nil {
		t.Fatal(err)
	}
}

func TestEveryConnectionBecomesProfile(t *testing.T) {
	dir := setupCatalog(t)
	source := fixture + strings.ReplaceAll(fixture, "local-db", "second-db") + "tools = ['nvim']\n" + strings.ReplaceAll(fixture, "local-db", "third-db") + "tools = ['rainfrog']\n"
	if err := os.WriteFile(filepath.Join(dir, "local.toml"), []byte(source), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := initializeSource(dir); err != nil {
		t.Fatal(err)
	}
	if _, err := syncCatalog(); err != nil {
		t.Fatal(err)
	}
	var config struct {
		Profiles map[string]struct{}
	}
	if _, err := toml.DecodeFile(filepath.Join(configBase(), "db", "harlequin.toml"), &config); err != nil {
		t.Fatal(err)
	}
	if len(config.Profiles) != 3 {
		t.Fatal("connections were filtered")
	}
	for _, name := range []string{"local_db", "second_db", "third_db"} {
		if _, ok := config.Profiles[name]; !ok {
			t.Fatalf("missing profile: %s", name)
		}
	}
}

func TestValidationBeforeWrites(t *testing.T) {
	dir := setupCatalog(t)
	if err := initializeSource(dir); err != nil {
		t.Fatal(err)
	}
	if _, err := syncCatalog(); err != nil {
		t.Fatal(err)
	}
	output := filepath.Join(configBase(), "db", "harlequin.toml")
	before, err := os.ReadFile(output)
	if err != nil {
		t.Fatal(err)
	}
	auxiliary := filepath.Join(configBase(), "db", "rainfrog_config.toml")
	if err := os.WriteFile(auxiliary, []byte("# Generated by db sync. Do not edit.\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "duplicate.toml"), []byte(fixture), 0o600); err != nil {
		t.Fatal(err)
	}
	if _, err := syncCatalog(); err == nil {
		t.Fatal("duplicate IDs accepted")
	}
	after, err := os.ReadFile(output)
	if err != nil || string(before) != string(after) {
		t.Fatal("invalid catalog changed output")
	}
	if _, err := os.Stat(auxiliary); err != nil {
		t.Fatal("invalid catalog cleaned auxiliary output")
	}
}

func TestDefaultSourceAndInvalidArgs(t *testing.T) {
	setupCatalog(t)
	source, err := sourcePath()
	if err != nil || source != filepath.Join(configBase(), "db", "connections") {
		t.Fatal("wrong default")
	}
	for _, args := range [][]string{
		{"invalid"}, {"sync"}, {"--select"}, {"--preview-tool", "harlequin"},
		{"--preview-project", "harlequin", "local"}, {"--preview-connection", "harlequin", "local-db"},
		{"default"}, {"init"}, {"init", "--source"},
	} {
		code, err := Run(args)
		if code != 2 || err != nil {
			t.Fatalf("invalid command %q tried to generate: %d %v", args, code, err)
		}
	}
	if err := initializeSource(t.TempDir()); err == nil {
		t.Fatal("empty source accepted")
	}
	if _, err := os.Stat(defaultConfigPath()); !os.IsNotExist(err) {
		t.Fatal("failed init wrote config")
	}
}

func TestRenderDriversAndEscaping(t *testing.T) {
	setupCatalog(t)
	catalog := map[string]connection{
		"test-h2":      {Driver: "h2", URL: "jdbc:h2:mem:test", Username: "sa", Password: "h2-secret"},
		"test-vertica": {Driver: "vertica", Host: "localhost", Port: 5433, Database: "demo", Password: "a;b}"},
	}
	output, err := renderCatalog(catalog)
	if err != nil {
		t.Fatal(err)
	}
	var parsed struct {
		Profiles map[string]struct {
			Adapter  string
			ConnStr  []string `toml:"conn_str"`
			User     string
			Password string
			Limit    int
		}
	}
	if _, err := toml.Decode(string(output), &parsed); err != nil {
		t.Fatal(err)
	}
	h2 := parsed.Profiles["test_h2"]
	vertica := parsed.Profiles["test_vertica"]
	if h2.Adapter != "h2" || h2.User != "sa" || h2.Password != "h2-secret" || h2.Limit != 1000 || len(h2.ConnStr) != 1 || h2.ConnStr[0] != "jdbc:h2:mem:test" {
		t.Fatal("incorrect H2 profile")
	}
	if vertica.Adapter != "odbc-vertica" || vertica.Limit != 1000 || len(vertica.ConnStr) != 1 || vertica.ConnStr[0] != "DRIVER={Vertica};SERVER={localhost};PORT=5433;DATABASE={demo};UID={};PWD={a;b}}}" {
		t.Fatal("incorrect Vertica profile or ODBC escaping")
	}
}

func TestRetiredAuxiliaryOwnership(t *testing.T) {
	for _, tc := range []struct {
		name    string
		content string
		remove  bool
	}{
		{"current marker", "Generated by harlequin-config. Do not edit.\n", true},
		{"old marker", "Generated by db sync. Do not edit.\n", true},
		{"manual", "Hand maintained\n", false},
		{"marker suffix", "Generated by harlequin-config. Do not edit. manually\n", false},
		{"marker not first", "Hand maintained\n# Generated by harlequin-config. Do not edit.\n", false},
		{"unterminated marker", "Generated by harlequin-config. Do not edit.", false},
	} {
		for _, output := range []struct {
			name    string
			comment string
		}{
			{"rainfrog_config.toml", "# "},
			{"nvim/local.lua", "-- "},
		} {
			t.Run(tc.name+"/"+output.name, func(t *testing.T) {
				dir := setupCatalog(t)
				if err := initializeSource(dir); err != nil {
					t.Fatal(err)
				}
				path := filepath.Join(configBase(), "db", output.name)
				content := []byte(output.comment + tc.content)
				if err := storage.WritePrivate(path, content); err != nil {
					t.Fatal(err)
				}
				if _, err := syncCatalog(); err != nil {
					t.Fatal(err)
				}
				after, err := os.ReadFile(path)
				if tc.remove {
					if !os.IsNotExist(err) {
						t.Fatal("owned auxiliary output retained")
					}
				} else if err != nil || string(after) != string(content) {
					t.Fatal("manual auxiliary output changed")
				}
			})
		}
	}
}

func TestRetiredAuxiliaryPreservesSymlinks(t *testing.T) {
	for _, tc := range []struct {
		name      string
		path      string
		content   string
		directory bool
		dangling  bool
	}{
		{name: "rainfrog file", path: "rainfrog_config.toml", content: "# Generated by harlequin-config. Do not edit.\n"},
		{name: "Neovim file", path: "nvim/local.lua", content: "-- Generated by db sync. Do not edit.\n"},
		{name: "Neovim directory", path: "nvim", content: "-- Generated by harlequin-config. Do not edit.\n", directory: true},
		{name: "dangling rainfrog", path: "rainfrog_config.toml", dangling: true},
		{name: "dangling Neovim file", path: "nvim/local.lua", dangling: true},
		{name: "dangling Neovim directory", path: "nvim", dangling: true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := setupCatalog(t)
			if err := initializeSource(dir); err != nil {
				t.Fatal(err)
			}
			target := filepath.Join(t.TempDir(), "target")
			file := target
			if tc.directory {
				if err := os.Mkdir(target, 0o700); err != nil {
					t.Fatal(err)
				}
				file = filepath.Join(target, "local.lua")
			}
			if !tc.dangling {
				if err := os.WriteFile(file, []byte(tc.content), 0o600); err != nil {
					t.Fatal(err)
				}
			}
			path := filepath.Join(configBase(), "db", tc.path)
			if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
				t.Fatal(err)
			}
			if err := os.Symlink(target, path); err != nil {
				t.Fatal(err)
			}
			if _, err := syncCatalog(); err != nil {
				t.Fatal(err)
			}
			if link, err := os.Readlink(path); err != nil || link != target {
				t.Fatal("auxiliary symlink changed")
			}
			if !tc.dangling {
				if data, err := os.ReadFile(file); err != nil || string(data) != tc.content {
					t.Fatal("auxiliary symlink target changed")
				}
			}
		})
	}
}
