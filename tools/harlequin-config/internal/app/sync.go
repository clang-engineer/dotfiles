package app

import (
	"bytes"
	"errors"
	"os"
	"path/filepath"
	"strings"

	"github.com/BurntSushi/toml"

	"github.com/clang-engineer/dotfiles/tools/harlequin-config/internal/catalog"
	"github.com/clang-engineer/dotfiles/tools/harlequin-config/internal/storage"
)

func loadConnections() (map[string]connection, error) {
	path, err := sourcePath()
	if err != nil {
		return nil, err
	}
	return catalog.Read(path)
}

func renderCatalog(catalog map[string]connection) ([]byte, error) {
	cfg, _, err := loadDBConfig()
	if err != nil {
		return nil, err
	}
	// The catalog owns connections; preserve each native profile's local theme.
	var previous struct {
		Profiles map[string]struct{ Theme string }
	}
	path := filepath.Join(configBase(), "db", "harlequin.toml")
	if _, err := toml.DecodeFile(path, &previous); err != nil && !errors.Is(err, os.ErrNotExist) {
		return nil, err
	}
	keymaps := make([]string, 0, len(cfg.HarlequinKeymaps))
	for _, keymap := range cfg.HarlequinKeymaps {
		if keymap = strings.TrimSpace(keymap); keymap != "" {
			keymaps = append(keymaps, keymap)
		}
	}
	profiles := make(map[string]any, len(catalog))
	for id, c := range catalog {
		profile := harlequinProfile(c)
		profile["theme"] = "dracula"
		if theme := previous.Profiles[strings.ReplaceAll(id, "-", "_")].Theme; theme != "" {
			profile["theme"] = theme
		}
		if len(keymaps) != 0 {
			profile["keymap_name"] = keymaps
		}
		profiles[strings.ReplaceAll(id, "-", "_")] = profile
	}
	data, err := storage.EncodeTOML(map[string]any{"profiles": profiles})
	if err != nil {
		return nil, err
	}
	return append([]byte("# Generated by harlequin-config. Do not edit.\n"), data...), nil
}

func syncCatalog() (map[string]connection, error) {
	catalog, err := loadConnections()
	if err != nil {
		return nil, err
	}
	output, err := renderCatalog(catalog)
	if err != nil {
		return nil, err
	}
	root := filepath.Join(configBase(), "db")
	path := filepath.Join(root, "harlequin.toml")
	existing, err := os.ReadFile(path)
	info, statErr := os.Lstat(path)
	if err != nil || statErr != nil || !info.Mode().IsRegular() || info.Mode().Perm() != 0o600 || !bytes.Equal(existing, output) {
		if err := storage.WritePrivate(path, output); err != nil {
			return nil, err
		}
	}
	if err := removeGeneratedAuxiliary(filepath.Join(root, "rainfrog_config.toml"), "#"); err != nil {
		return nil, err
	}
	// Do not traverse a user's Neovim directory symlink or follow file symlinks.
	nvim := filepath.Join(root, "nvim")
	info, err = os.Lstat(nvim)
	if errors.Is(err, os.ErrNotExist) {
		return catalog, nil
	}
	if err != nil {
		return nil, err
	}
	if info.IsDir() {
		stale, err := filepath.Glob(filepath.Join(nvim, "*.lua"))
		if err != nil {
			return nil, err
		}
		for _, path := range stale {
			if err := removeGeneratedAuxiliary(path, "--"); err != nil {
				return nil, err
			}
		}
	}
	return catalog, nil
}

func removeGeneratedAuxiliary(path, comment string) error {
	info, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	if !info.Mode().IsRegular() {
		return nil
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	for _, generator := range []string{"harlequin-config", "db sync"} {
		if bytes.HasPrefix(data, []byte(comment+" Generated by "+generator+". Do not edit.\n")) {
			return os.Remove(path)
		}
	}
	return nil
}
